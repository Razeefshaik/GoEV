// Builds the static frontend for Netlify from the files Spring Boot serves locally,
// so there is a single source of truth (src/main/resources). No npm dependencies.
//
//   GOEV_API_URL=https://goev-backend.onrender.com node frontend/build.mjs
//
// Output: frontend/dist/
//   index.html  <- templates/dashboard.html   (served at /)
//   v2g.html    <- templates/v2g.html         (served at /v2g via netlify.toml)
//   config.js   <- generated with the backend URL
//   v2g/**      <- static/v2g/**
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const resources = join(root, "src", "main", "resources");
const dist = join(root, "frontend", "dist");

const apiUrl = (process.env.GOEV_API_URL || "").trim().replace(/\/+$/, "");
if (!apiUrl) {
  const msg = "GOEV_API_URL is not set: the site will call its own origin and API requests will fail.";
  if (process.env.NETLIFY) {
    console.error(`ERROR: ${msg} Set it in Netlify > Site configuration > Environment variables.`);
    process.exit(1);
  }
  console.warn(`WARNING: ${msg}`);
} else if (!/^https?:\/\//.test(apiUrl)) {
  console.error(`ERROR: GOEV_API_URL must start with http:// or https:// (got "${apiUrl}").`);
  process.exit(1);
}

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

cpSync(join(resources, "static"), dist, { recursive: true });

// Thymeleaf attributes are inert in a browser, but strip them so the output is plain HTML.
const stripThymeleaf = (html) =>
  html.replace(/\s+xmlns:th="[^"]*"/g, "").replace(/\s+th:inline="[^"]*"/g, "");

for (const [template, out] of [["dashboard.html", "index.html"], ["v2g.html", "v2g.html"]]) {
  const html = readFileSync(join(resources, "templates", template), "utf8");
  writeFileSync(join(dist, out), stripThymeleaf(html));
}

writeFileSync(
  join(dist, "config.js"),
  `// Generated by frontend/build.mjs at ${new Date().toISOString()}\n` +
    `window.GOEV_API_BASE = ${JSON.stringify(apiUrl)};\n`,
);

console.log(`Frontend built into ${dist} (API: ${apiUrl || "same origin"})`);
